def calculate_fundamental_health_score(metrics: dict) -> dict:
    """
    حساب درجة الجدارة المالية والتقييم (0-100) للمستثمر في البورصة المصرية:
    - التقييم ومكرر الربحية (30 نقطة)
    - مضاعف القيمة الدفترية P/B (20 نقطة)
    - عائد التوزيعات النقدية Dividend Yield (25 نقطة)
    - العائد على حقوق الملكية ROE وجودة الملاءة (25 نقطة)
    """
    score = 50
    reasons = []

    pe = metrics.get("مكرر_الربحية_PE")
    if pe is not None:
        if pe <= 0:
            score -= 25
            reasons.append("الشركة تحقق خسائر (مكرر ربحية سالب) ⚠️")
        elif pe < 5.0:
            score += 25
            reasons.append(f"مكرر ربحية رخيص جداً واستثنائي ({pe:.1f}) — استرداد رأس المال سريع")
        elif pe < 8.0:
            score += 18
            reasons.append(f"مكرر ربحية جذاب وأقل من متوسط السوق ({pe:.1f})")
        elif pe < 14.0:
            score += 5
            reasons.append(f"مكرر ربحية في النطاق العادل والمقبول ({pe:.1f})")
        else:
            score -= 10
            reasons.append(f"مكرر ربحية مرتفع نسبياً ({pe:.1f}) — تداول بعلاوة سعرية")

    pb = metrics.get("السعر_إلى_القيمة_الدفترية_PB")
    if pb is not None:
        if pb < 1.0:
            score += 20
            reasons.append(f"السهم يتداول بأقل من قيمته الدفترية ({pb:.2f}x) — هامش أمان حقيقي")
        elif pb < 1.5:
            score += 15
            reasons.append(f"مضاعف قيمة دفترية ممتاز ({pb:.2f}x)")
        elif pb < 2.5:
            score += 5
            reasons.append(f"مضاعف قيمة دفترية معتدل ({pb:.2f}x)")
        else:
            score -= 5
            reasons.append(f"مضاعف قيمة دفترية أعلى من المتوسط ({pb:.2f}x)")

    dy = metrics.get("عائد_التوزيعات")
    if dy is not None:
        dy_pct = dy * 100
        if dy_pct >= 8.0:
            score += 25
            reasons.append(f"عائد توزيعات كاش استثنائي ({dy_pct:.1f}%) — حماية قوية من التضخم")
        elif dy_pct >= 5.0:
            score += 18
            reasons.append(f"عائد توزيعات نقدية جيد جداً ({dy_pct:.1f}%)")
        elif dy_pct >= 2.0:
            score += 8
            reasons.append(f"توزيعات نقدية دورية مقبولة ({dy_pct:.1f}%)")
        else:
            reasons.append("توزيعات كاش ضئيلة أو تعيد استثمار أرباحها للنمو")

    roe = metrics.get("العائد_على_حقوق_الملكية_ROE")
    if roe is not None:
        roe_pct = roe * 100
        if roe_pct >= 30:
            score += 20
            reasons.append(f"كفاءة إدارة استثنائية: عائد على حقوق الملكية ROE ضخم ({roe_pct:.0f}%)")
        elif roe_pct >= 18:
            score += 12
            reasons.append(f"عائد جيد على حقوق الملكية ({roe_pct:.0f}%)")

    score = max(10, min(98, score))

    if score >= 75:
        verdict = "سهم قيمة ممتاز وتوزيعات قوية 🌟"
        color = "#00c853"
    elif score >= 60:
        verdict = "جدارة مالية جيدة وتقييم عادل 🟢"
        color = "#66bb6a"
    elif score >= 45:
        verdict = "تقييم متوسط / نمو 🟡"
        color = "#ffb300"
    else:
        verdict = "تقييم متضخم أو مخاطر مالية ⚠️"
        color = "#e53935"

    return {
        "health_score": score,
        "verdict": verdict,
        "color": color,
        "reasons": reasons,
    }
